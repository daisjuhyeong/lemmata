"""Fixture-backed stand-in for engine.api.Engine (web-eng development and UI tests).

Same facade signatures as data-model section 13, served from app/tests/fixtures/api/*.json.
State changes live in memory only. Variant "large" generates a ~300 node / ~500 edge graph
for performance checks. This module is not the engine and does not replace it.
"""
from __future__ import annotations

import copy
import json
import random
from collections import deque
from pathlib import Path

try:
    from rmap.engine.errors import BadRequest, NotFound
except ImportError:  # engine not present yet
    from rmap.engine_errors import BadRequest, NotFound

FIX = Path(__file__).resolve().parents[2] / "tests" / "fixtures"
STATES = ("unreviewed", "reviewed", "needs_fixing", "ignored")
PHRASE = {"reads": "reads", "produced_by": "is produced by", "traces_to": "traces to", "includes": "includes",
          "generated_by": "is generated by", "executes": "runs", "imports": "imports", "value_match": "was linked by you to"}


def _load(name):
    return json.loads((FIX / "api" / name).read_text(encoding="utf-8"))


def _large():
    """Deterministic big graph in the shape of the real code-only repo plus a paper."""
    rnd = random.Random(7)
    nodes, edges = [], []

    def add(id, kind, layer, repo, name, path, line=None, attrs=None):
        nodes.append({"id": id, "kind": kind, "layer": layer, "repo": repo, "name": name, "detail": "",
                      "loc": {"path": path, "line": line, "end_line": None}, "hash": "blob:" + "%040x" % rnd.getrandbits(160),
                      "attrs": attrs or {}})

    def link(a, kind, b, status="detected"):
        prop = kind in ("includes", "generated_by", "traces_to", "produced_by", "executes", "reads", "imports") and status != "proposed"
        edges.append({"id": "%s|%s|%s" % (a, kind, b), "from": a, "to": b, "kind": kind, "status": status, "propagates": prop,
                      "evidence": [{"repo": "code", "path": "x.py", "line": 1, "text": "x", "role": "import", "page": None}], "reason": None})

    add("thesis", "thesis", 0, "paper", "Thesis", "main.tex", 6, {"text": "thesis"})
    for i in range(1, 4):
        add("rq:RQ%d" % i, "rq", 1, "paper", "RQ%d" % i, "main.tex", 9 + i, {"text": "q"})
        link("thesis", "contains", "rq:RQ%d" % i)
    secs = []
    for i in range(1, 13):
        sid = "tex:sec:s%d" % i
        add(sid, "section", 2, "paper", "§%d Section %d" % (i, i), "main.tex", 20 * i,
            {"level": 1, "number": str(i), "in_appendix": i > 10, "title": "Section %d" % i, "tex_label": "sec:s%d" % i})
        link("thesis", "contains", sid)
        secs.append(sid)
    floats = []
    for i in range(1, 25):
        fid = "tex:fig:f%d" % i
        kind = "figure" if i % 2 else "table"
        add(fid, kind, 3, "paper", ("Fig. %d" if i % 2 else "Table %d") % i, "main.tex", 15 * i, {"number": str(i), "caption": "Item %d" % i})
        link(rnd.choice(secs), "contains", fid)
        floats.append(fid)
    dirs = ["experiments/exp%d" % d for d in range(1, 7)] + ["metrics", "models", "datasets"]
    results = []
    for i in range(70):
        d = rnd.choice(dirs[:6])
        rid = "file:code/%s/results/r%d.csv" % (d, i)
        add(rid, "result", 4, "code", "%s/results/r%d.csv" % (d, i), "%s/results/r%d.csv" % (d, i), None, {"size": 100, "ext": ".csv", "binary": False})
        results.append(rid)
    for i, fid in enumerate(floats):
        for r in rnd.sample(results, 2):
            link(fid, "traces_to", r)
    runs = []
    for i in range(18):
        rid = "run:code/run%d" % i
        add(rid, "run", 5, "code", "run run%d" % i, "runs/run%d.json" % i, None, {"command": "python x.py", "started_at": "2026-09-30T14:00:00+09:00"})
        runs.append(rid)
    codes = []
    for i in range(150):
        d = rnd.choice(dirs)
        cid = "file:code/%s/m%d.py" % (d, i)
        add(cid, "code", 6, "code", "%s/m%d.py" % (d, i), "%s/m%d.py" % (d, i), None, {"size": 900, "ext": ".py"})
        codes.append(cid)
    for r in results:
        link(r, "produced_by", rnd.choice(runs))
    for r in runs:
        link(r, "executes", rnd.choice(codes))
    for c in codes:
        for t in rnd.sample(codes, 3):
            if t != c:
                link(c, "imports", t)
    for i in range(12):
        cid = "file:code/config/c%d.yaml" % i
        add(cid, "config", 6, "code", "config/c%d.yaml" % i, "config/c%d.yaml" % i, None, {"size": 90, "ext": ".yaml"})
        link(rnd.choice(runs), "reads", cid)
    for i in range(10):
        key = "ref%d" % i
        add("ref:" + key, "reference", None, "paper", "[%s]" % key, "refs.bib", 4 * i + 1, {"bib_key": key, "title": "T%d" % i, "year": 2020, "lookup": "matched"})
        link(rnd.choice(secs), "cites", "ref:" + key)
    uniq = {}
    for e in edges:
        uniq[e["id"]] = e
    edges = sorted(uniq.values(), key=lambda e: e["id"])
    nodes.sort(key=lambda n: (99 if n["layer"] is None else n["layer"], n["id"]))
    return nodes, edges


class FixtureEngine:
    def __init__(self, project_root="", online=False, variant="sample"):
        self.online = online
        self.variant = variant
        self._project = _load("project.json")
        files = FIX / "files"
        self._project["root"] = str(files)
        for r in self._project["repos"]:
            r["abs_path"] = str(files / r["path"])
        self._graph = _load("graph.json")
        self._events = _load("events.json")
        self._findings = _load("findings.json")
        self._alarms = _load("alarms.json")
        self._checkpoints = _load("checkpoints.json")
        self._triage = _load("triage.json")
        self._analysis = _load("analyze.json")
        self._diffs = _load("diffs.json")
        self._changed = {}
        self._snap_edges()
        if variant == "large":
            n, e = _large()
            self._graph["nodes"], self._graph["edges"] = n, e
            codes = [x["id"] for x in n if x["kind"] == "code"]
            self._alarms["groups"] = []
            self._alarms["groups"].append(self._mkgroup("A1", "ev:commit:code:aaaaaaaaaaaa", [codes[3]]))
            self._alarms["groups"].append(self._mkgroup("A2", "ev:commit:code:bbbbbbbbbbbb", [codes[40], codes[41]]))
            self._alarms["groups"][1]["flags"] = [{"code": "message_claims_no_change", "confidence": "low", "phrase": "no functional changes",
                                                    "text": "Message says \"no functional changes\"; content changed in 2 files."}]
            self._recompute()
            self._project["name"] = "Large fixture"
            self._project["counts"].update({"nodes": len(n), "edges": len(e)})
            self._snap_edges()
            self._recompute()
        self._cp_n = 1

    def _snap_edges(self):
        self._edge = {e["id"]: e for e in self._graph["edges"]}
        self._node = {n["id"]: n for n in self._graph["nodes"]}

    def _mkgroup(self, disp, gid, changed):
        return {"id": gid, "display": disp,
                "cause": {"event_id": gid, "kind": "commit", "repo": "code", "rev": gid[-12:] * 3 + "abcd", "short": gid[-12:][:7],
                          "time": "2026-10-0%dT10:00:00+09:00" % (3 if disp == "A1" else 4), "subject": "fixture change " + disp, "files": ["m.py"]},
                "changed": [{"node_id": c, "change": "content_changed", "hash_checkpoint": "blob:" + "0" * 40, "hash_now": "blob:" + "1" * 40, "also_changed_in": []} for c in changed],
                "removed": [], "downstream": [], "flags": []}

    # --- propagation (data-model 8, steps 4-6)
    def _recompute(self):
        rev = {}
        for e in self._graph["edges"]:
            if e["status"] in ("detected", "approved") and (e["propagates"] or (e["kind"] == "value_match" and e["status"] == "approved")):
                rev.setdefault(e["to"], []).append(e)
        for g in self._alarms["groups"]:
            ch = {c["node_id"] for c in g["changed"]}
            seen = {c: 0 for c in ch}
            via = {}
            dq = deque(sorted(ch))
            while dq:
                cur = dq.popleft()
                for e in sorted(rev.get(cur, []), key=lambda x: x["id"]):
                    if e["from"] not in seen:
                        seen[e["from"]] = seen[cur] + 1
                        via[e["from"]] = e["id"]
                        dq.append(e["from"])
            down = []
            for nid, d in seen.items():
                if nid in ch:
                    continue
                kind = self._node[nid]["kind"] if getattr(self, "_node", None) and nid in self._node else None
                oi = (self._identical(nid)) if kind in ("result", "asset") else None
                down.append({"node_id": nid, "depth": d, "via": via[nid], "output_identical": oi})
            g["downstream"] = sorted(down, key=lambda x: (x["depth"], x["node_id"]))
        gs = self._alarms["groups"]
        self._alarms["summary"] = {"groups": len(gs), "changed": sum(len(g["changed"]) for g in gs), "removed": 0,
                                   "downstream": sum(len(g["downstream"]) for g in gs), "flagged_nodes": len({x["node_id"] for g in gs for x in g["changed"] + g["downstream"]})}

    def _identical(self, nid):
        return nid != "file:code/results/never"

    # --- facade
    def scan(self):
        self._project["scanned_at"] = self._graph["scanned_at"]
        return self.project()

    def project(self):
        p = copy.deepcopy(self._project)
        p["counts"]["proposed"] = sum(1 for e in self._graph["edges"] if e["status"] == "proposed")
        p["counts"]["alarm_groups"] = len(self._alarms["groups"])
        p["counts"]["findings"] = len(self._findings["findings"])
        cp = self._alarms.get("checkpoint")
        p["checkpoint"] = cp
        return p

    def graph(self):
        return self._graph

    def events(self, after_checkpoint=False):
        ev = self._events["events"]
        if after_checkpoint:
            ev = [e for e in ev if e["after_checkpoint"]]
        return {"schema": "rmap.events/1", "events": ev}

    def findings(self):
        return self._findings

    def alarms(self):
        return self._alarms

    def checkpoints(self):
        return self._checkpoints

    def create_checkpoint(self, note="", at=None, created_at=None, cp_id=None):
        if at:
            for k in at:
                if k not in {r["id"] for r in self._project["repos"]}:
                    raise BadRequest("unknown repo: %s" % k)
        self._cp_n += 1
        cid = cp_id or "cp%d" % self._cp_n
        for c in self._checkpoints["checkpoints"]:
            c["active"] = False
        base = self._checkpoints["checkpoints"][0]
        cp = {"id": cid, "created_at": created_at or "2026-11-04T16:%02d:00+09:00" % (self._cp_n % 60), "note": note,
              "repos": copy.deepcopy(base["repos"]), "node_count": len(self._graph["nodes"]), "active": True}
        self._checkpoints["checkpoints"].insert(0, cp)
        self._checkpoints["active"] = cid
        self._alarms["checkpoint"] = {"id": cid, "created_at": cp["created_at"], "note": note}
        self._alarms["groups"] = []
        self._recompute()
        return {"checkpoint": cp, "alarms": self._alarms}

    def checkpoints_view(self):
        return self._checkpoints

    def triage(self):
        return self._triage

    def set_triage(self, target_type, target_id, state, note=""):
        if target_type not in ("node", "finding") or state not in STATES:
            raise BadRequest("bad triage request")
        known = (target_id in self._node) if target_type == "node" else any(f["id"] == target_id for f in self._findings["findings"])
        if not known:
            raise NotFound("unknown %s: %s" % (target_type, target_id))
        key = "%s:%s" % (target_type, target_id)
        prev = self._triage["entries"].get(key)
        at = "2026-11-04T15:%02d:00+09:00" % (len(prev["history"]) + 3 if prev else 3)
        h = (self._node[target_id]["hash"] if target_type == "node" else
             next(f["fingerprint"] for f in self._findings["findings"] if f["id"] == target_id))
        entry = prev or {"target_type": target_type, "target_id": target_id, "history": []}
        entry.update({"state": state, "note": note, "hash_at_triage": h, "updated_at": at})
        entry["history"].append({"state": state, "note": note, "at": at, "hash": h})
        self._triage["entries"][key] = entry
        out = copy.deepcopy(entry)
        out["effective_state"], out["outdated"] = state, False
        return {"entry": out}

    def decide_link(self, edge_id, decision):
        e = self._edge.get(edge_id)
        if e is None:
            raise NotFound("unknown edge")
        if decision not in ("approved", "rejected", "proposed") or not (e["kind"] == "value_match"):
            raise BadRequest("only proposed links can be decided")
        e["status"] = decision
        e["propagates"] = decision == "approved"
        self._triage["links"][edge_id] = {"decision": decision, "at": "2026-11-04T15:05:00+09:00", "history": [{"decision": decision, "at": "2026-11-04T15:05:00+09:00"}]}
        self._recompute()
        return {"edge": e, "alarms": self._alarms}

    def analyze(self, group_id, node_id):
        g = next((g for g in self._alarms["groups"] if g["id"] == group_id), None)
        if g is None:
            raise NotFound("unknown group")
        ch = {c["node_id"] for c in g["changed"]}
        down = {d["node_id"]: d for d in g["downstream"]}
        if node_id not in ch and node_id not in down:
            raise NotFound("node is not in this group")
        nodes, edges = [node_id], []
        cur = node_id
        while cur not in ch:
            eid = down[cur]["via"]
            edges.append(eid)
            cur = self._edge[eid]["to"]
            nodes.append(cur)
        nodes.reverse()
        edges.reverse()
        diffs = [self._diffs[n] for n in nodes if n in self._diffs]
        out = []
        for i, eid in enumerate(edges):
            e = self._edge[eid]
            out.append("%s %s %s." % (self._node[e["from"]]["name"], PHRASE.get(e["kind"], e["kind"]), self._node[e["to"]]["name"]))
        expl = "%s changed in %s (\"%s\"). %s" % (self._node[nodes[0]]["name"], g["cause"]["short"], g["cause"]["subject"], " ".join(reversed(out)))
        return {"group_id": group_id, "node_id": node_id, "chain": {"nodes": nodes, "edges": edges}, "diffs": diffs,
                "explanation": expl, "ai": {"available": False, "label": "Ask Claude why — not available in this demo"}}

    def export_bundle(self):
        return {"project": self.project(), "graph": self.graph(), "events": self.events(), "findings": self.findings(),
                "alarms": self.alarms(), "checkpoints": self.checkpoints(), "triage": self.triage()}
